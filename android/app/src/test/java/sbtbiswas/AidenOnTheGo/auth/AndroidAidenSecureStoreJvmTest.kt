    @Test
    fun durableOperationsUseSynchronousCommitAndThrowOnFalseReturn() {
        val (backend, masterAead) = createProvisionedBackend()
        val store = openStoreOverBackend(backend, masterAead)

        store.setCredentialDurably("durable-key", "durable-val")
        assertEquals(1, backend.commitWriteCount)
        assertEquals(0, backend.asyncWriteCount)
        assertEquals("durable-val", store.getCredential("durable-key"))

        store.removeCredentialDurably("durable-key")
        assertEquals(1, backend.commitRemoveCount)
        assertNull(store.getCredential("durable-key"))

        backend.commitResult = false
        val saveError = assertThrows(IllegalStateException::class.java) {
            store.setCredentialDurably("durable-key", "will-fail")
        }
        assertEquals("Secure state could not be saved", saveError.message)

        val removeError = assertThrows(IllegalStateException::class.java) {
            store.removeCredentialDurably("durable-key")
        }
        assertEquals("Secure state could not be removed", removeError.message)
    }

    @Test
    fun tamperedCiphertextsRaiseSecurityExceptionSoBotJournalNeverOverwritesPendingIdentity() {
        val (backend, masterAead) = createProvisionedBackend()
        val store = openStoreOverBackend(backend, masterAead)
        val pairedAt = Instant.parse("2026-06-10T08:00:00Z")
        val journal = AidenBotWatchJournalStore(store)
            .journal("inst-jvm-tamper", "dev-jvm-tamper", pairedAt, "bot-a") { true }
        journal.write("pending-identity-must-survive")

        val scope = botJournalScope("bot-watches", "inst-jvm-tamper", "dev-jvm-tamper", pairedAt)
        val encryptedKey = backend.entries.keys.single { !isReservedSecureStoreKey(it) }
        val validCiphertext = backend.entries.getValue(encryptedKey)

        // 1. Flip a byte in the AES-GCM tag -> SecurityException, and write() refuses to overwrite.
        val flipped = Base64.decode(validCiphertext, Base64.DEFAULT).also {
            it[it.lastIndex] = (it.last().toInt() xor 0xFF).toByte()
        }
        val tamperedCiphertext = Base64.encode(flipped)
        backend.entries[encryptedKey] = tamperedCiphertext

        assertThrows(SecurityException::class.java) { store.getCredential(scope) }
        assertThrows(SecurityException::class.java) { journal.read() }
        assertThrows(SecurityException::class.java) { journal.write("replacement-identity") }
        assertFalse(runCatching { journal.replace(null, "replacement-identity") }.isSuccess)
        assertEquals(tamperedCiphertext, backend.entries[encryptedKey])

        // 2. Non-string EncryptedType payload (e.g. INT = 3) encrypted with valid AEAD key -> SecurityException.
        val config = RegistryConfiguration.get()
        val valueAead = TinkProtoKeysetFormat.parseEncryptedKeyset(
            Hex.decode(backend.entries.getValue(AIDEN_VALUE_KEYSET_ALIAS)),
            masterAead,
            ByteArray(0),
            config
        ).getPrimitive(config, Aead::class.java)
        val wrongTypePayload = ByteBuffer.allocate(12).putInt(3).putInt(42).putInt(0).array()
        backend.entries[encryptedKey] = Base64.encode(
            valueAead.encrypt(wrongTypePayload, encryptedKey.toByteArray(Charsets.UTF_8))
        )
        assertThrows(SecurityException::class.java) { store.getCredential(scope) }

        // 3. Truncated payload (< 8 bytes) encrypted with valid AEAD key -> SecurityException.
        backend.entries[encryptedKey] = Base64.encode(
            valueAead.encrypt(ByteArray(4), encryptedKey.toByteArray(Charsets.UTF_8))
        )
        assertThrows(SecurityException::class.java) { store.getCredential(scope) }

        // 4. Length mismatch in payload header -> SecurityException.
        val badLengthPayload = ByteBuffer.allocate(10).putInt(0).putInt(99).putShort(1).array()
        backend.entries[encryptedKey] = Base64.encode(
            valueAead.encrypt(badLengthPayload, encryptedKey.toByteArray(Charsets.UTF_8))
        )
        assertThrows(SecurityException::class.java) { store.getCredential(scope) }

        // 5. Reserved key access -> SecurityException.
        assertThrows(SecurityException::class.java) { store.getCredential(AIDEN_KEY_KEYSET_ALIAS) }
        assertThrows(SecurityException::class.java) { store.setCredentialDurably(AIDEN_VALUE_KEYSET_ALIAS, "x") }
        assertThrows(SecurityException::class.java) { store.removeCredentialDurably(AIDEN_KEY_KEYSET_ALIAS) }
    }

    @Test
    fun clearAllRemovesSecretsAndJournalsWhileKeepingKeysetsValidForSubsequentWritesAndPairingRemoval() {
        val dir = Files.createTempDirectory("aiden-jvm-secure-store-").toFile()
        try {
            val (backend, masterAead) = createProvisionedBackend()
            val store = openStoreOverBackend(backend, masterAead)
            val installations = AidenInstallationStore(dir, store)
            val pairing = installations.addInstallation(
                AidenPairingExchange(
                    instanceId = "inst-jvm-clear",
                    deviceId = "dev-jvm-clear",
                    endpoint = "https://example.test/api/aiden/v1",
                    serverSpkiSha256 = "sha256/jvm",
                    credential = "desktop-secret",
                    capabilities = listOf(AidenRemoteCapability.BOT_READ)
                ),
                trust = null
            )
            AidenBotWatchJournalStore(store)
                .journal(pairing.instanceId, pairing.deviceId, pairing.createdAt, "bot-1") { true }
                .write("watch-uuid")
            AidenBotWatchJournalStore(store, "bot-peers", 1088)
                .journal(pairing.instanceId, pairing.deviceId, pairing.createdAt, "bot-1|peer|p1") { true }
                .write("peer-uuid")

            // Forgetting a pairing purges its credential and journals cleanly.
            installations.removeInstallation(pairing.id)
            assertNull(store.getCredential(pairing.credentialScope))
            assertNull(
                AidenBotWatchJournalStore(store)
                    .journal(pairing.instanceId, pairing.deviceId, pairing.createdAt, "bot-1") { true }
                    .read()
            )

            // Populate entries again, then clearAll() and verify keyset preservation.
            store.setCredential("scope-a", "secret-a")
            store.setCredentialDurably("scope-b", "secret-b")
            val keyKeyset = backend.entries.getValue(AIDEN_KEY_KEYSET_ALIAS)
            val valueKeyset = backend.entries.getValue(AIDEN_VALUE_KEYSET_ALIAS)

            store.clearAll()

            assertNull(store.getCredential("scope-a"))
            assertNull(store.getCredential("scope-b"))
            assertEquals(setOf(AIDEN_KEY_KEYSET_ALIAS, AIDEN_VALUE_KEYSET_ALIAS), backend.entries.keys)
            assertEquals(keyKeyset, backend.entries[AIDEN_KEY_KEYSET_ALIAS])
            assertEquals(valueKeyset, backend.entries[AIDEN_VALUE_KEYSET_ALIAS])

            store.setCredentialDurably("post-clear-scope", "post-clear-secret")
            assertEquals("post-clear-secret", store.getCredential("post-clear-scope"))
            assertEquals(
                "post-clear-secret",
                openStoreOverBackend(backend, masterAead).getCredential("post-clear-scope")
            )
        } finally {
            dir.deleteRecursively()
        }
    }

    @Test
    fun failsClosedWhenKeystoreOrKeysetValidationFails() {
        var fallbackPurges = 0
        val failedKeystoreStore = AndroidAidenSecureStore(
            purgeFallbackPreferences = { fallbackPurges++ },
            openCipherStore = { throw GeneralSecurityException("Keystore hardware unavailable") }
        )
        assertEquals(1, fallbackPurges)
        assertNull(failedKeystoreStore.getCredential("inst:dev"))
        assertThrows(IllegalStateException::class.java) {
            failedKeystoreStore.setCredential("inst:dev", "secret")
        }
        assertThrows(IllegalStateException::class.java) {
            failedKeystoreStore.setCredentialDurably("inst:dev", "secret")
        }
        failedKeystoreStore.removeCredential("inst:dev")
        failedKeystoreStore.removeCredentialDurably("inst:dev")
        failedKeystoreStore.clearAll()

        // Stripped keyset when user entries already exist must fail validation instead of minting new keys.
        val (backendWithStrippedKeyset, masterAead) = createProvisionedBackend()
        openStoreOverBackend(backendWithStrippedKeyset, masterAead).setCredentialDurably("inst:dev", "secret")
        backendWithStrippedKeyset.entries.remove(AIDEN_VALUE_KEYSET_ALIAS)
        assertThrows(GeneralSecurityException::class.java) {
            validateExistingPreferencesKeysets(backendWithStrippedKeyset, masterAead)
        }
        val strippedStore = openStoreOverBackend(backendWithStrippedKeyset, masterAead)
        assertNull(strippedStore.getCredential("inst:dev"))
        assertThrows(IllegalStateException::class.java) {
            strippedStore.setCredentialDurably("inst:dev", "overwrite")
        }

        // Cleartext keyset hex must also fail validation.
        val (backendWithCleartextKeyset, masterAead2) = createProvisionedBackend()
        val config = RegistryConfiguration.get()
        backendWithCleartextKeyset.entries[AIDEN_VALUE_KEYSET_ALIAS] = Hex.encode(
            TinkProtoKeysetFormat.serializeKeyset(
                KeysetHandle.generateNew(PredefinedAeadParameters.AES256_GCM, config),
                InsecureSecretKeyAccess.get(),
                config
            )
        )
        assertThrows(GeneralSecurityException::class.java) {
            validateExistingPreferencesKeysets(backendWithCleartextKeyset, masterAead2)
        }
    }

    private fun createProvisionedBackend(): Pair<FakeRawPreferencesBackend, Aead> {
        DeterministicAeadConfig.register()
        AeadConfig.register()
        val config = RegistryConfiguration.get()
        val masterAead = KeysetHandle.generateNew(PredefinedAeadParameters.AES256_GCM, config)
            .getPrimitive(config, Aead::class.java)
        val keyHandle = KeysetHandle.generateNew(PredefinedDeterministicAeadParameters.AES256_SIV, config)
        val valueHandle = KeysetHandle.generateNew(PredefinedAeadParameters.AES256_GCM, config)
        val backend = FakeRawPreferencesBackend(
            linkedMapOf(
                AIDEN_KEY_KEYSET_ALIAS to Hex.encode(
                    TinkProtoKeysetFormat.serializeEncryptedKeyset(keyHandle, masterAead, ByteArray(0), config)
                ),
                AIDEN_VALUE_KEYSET_ALIAS to Hex.encode(
                    TinkProtoKeysetFormat.serializeEncryptedKeyset(valueHandle, masterAead, ByteArray(0), config)
                )
            )
        )
        return backend to masterAead
    }

    private fun openStoreOverBackend(
        backend: FakeRawPreferencesBackend,
        masterAead: Aead,
        onPurgeFallback: () -> Unit = {}
    ): AndroidAidenSecureStore {
        return AndroidAidenSecureStore(
            purgeFallbackPreferences = onPurgeFallback,
            openCipherStore = {
                validateExistingPreferencesKeysets(backend, masterAead)
                val config = RegistryConfiguration.get()
                val keyHandle = TinkProtoKeysetFormat.parseEncryptedKeyset(
                    Hex.decode(backend.entries.getValue(AIDEN_KEY_KEYSET_ALIAS)),
                    masterAead,
                    ByteArray(0),
                    config
                )
                val valueHandle = TinkProtoKeysetFormat.parseEncryptedKeyset(
                    Hex.decode(backend.entries.getValue(AIDEN_VALUE_KEYSET_ALIAS)),
                    masterAead,
                    ByteArray(0),
                    config
                )
                TinkPreferencesStore(
                    backend = backend,
                    keyDeterministicAead = keyHandle.getPrimitive(config, DeterministicAead::class.java),
                    valueAead = valueHandle.getPrimitive(config, Aead::class.java)
                )
            }
        )
    }

    private fun botJournalScope(
        namespace: String,
        instanceId: String,
        deviceId: String,
        pairedAt: Instant
    ): String {
        val identity = "$instanceId\u001f$deviceId\u001f$pairedAt"
        val digest = MessageDigest.getInstance("SHA-256")
            .digest(identity.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
        return "aiden:$namespace:v1:$digest"
    }

    private class FakeRawPreferencesBackend(
        val entries: LinkedHashMap<String, String> = linkedMapOf()
    ) : RawPreferencesBackend {
        var commitResult: Boolean = true
        var asyncWriteCount: Int = 0
        var commitWriteCount: Int = 0
        var commitRemoveCount: Int = 0

        override fun allKeys(): Set<String> = entries.keys.toSet()

        override fun contains(key: String): Boolean = entries.containsKey(key)

        override fun getString(key: String): String? = entries[key]

        override fun putStringAsync(key: String, value: String) {
            asyncWriteCount++
            entries[key] = value
        }

        override fun putStringCommit(key: String, value: String): Boolean {
            commitWriteCount++
            if (!commitResult) return false
            entries[key] = value
            return true
        }

        override fun removeAsync(key: String) {
            entries.remove(key)
        }

        override fun removeCommit(key: String): Boolean {
            commitRemoveCount++
            if (!commitResult) return false
            entries.remove(key)
            return true
        }

        override fun removeManyAsync(keys: Collection<String>) {
            keys.forEach(entries::remove)
        }
    }
