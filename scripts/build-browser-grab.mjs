import { Buffer } from "node:buffer";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";
import { build } from "esbuild";

const rootDir = resolve(import.meta.dirname, "..");
const entryPoint = resolve(rootDir, "main/services/browser/grab-runtime/index.ts");
const outFile = resolve(rootDir, "main/services/browser/grab-runtime.generated.ts");

const result = await build({
  entryPoints: [entryPoint],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome128"],
  minify: true,
  write: false,
  legalComments: "none",
});

const output = result.outputFiles[0];
if (!output) {
  throw new Error("esbuild produced no output for grab-runtime.");
}

const source = output.text.trim();
const generated = [
  "// Generated by scripts/build-browser-grab.mjs — do not edit by hand.",
  `export const browserGrabRuntimeSource = ${JSON.stringify(source)};`,
  "",
].join("\n");

writeFileSync(outFile, generated, "utf8");
process.stdout.write(`Built ${outFile} (${Buffer.byteLength(source, "utf8")} bytes IIFE).\n`);
